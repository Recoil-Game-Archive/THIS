-- Starbase Init anim
function Init()
	permaStealth = 1
	local bodyemit0, bodyemit1 = piece("bodyemit0", "bodyemit1")
	local bay0, bay1 = piece("bay0", "bay1")
	local tp0, tp1, tp2 = piece("tp_1_1", "tp_1_2", "tp_1_3")
	Sleep(30 + 33) -- to let the MoveCtrl move it
	Turn(bay0, y_axis, math.rad(-25))
	Turn(bay1, y_axis, math.rad(155))
	Turn(bodyemit0, x_axis, math.rad(-90))
	Turn(bodyemit1, x_axis, math.rad(-90))
	EmitSfx(bodyemit0, 1027)
	EmitSfx(bodyemit1, 1027)
	Turn(tp0, y_axis, math.rad(30))
	Turn(tp1, y_axis, math.rad(150))
	Turn(tp2, y_axis, math.rad(270))
	Turn(tp0, x_axis, math.rad(-30))
	Turn(tp1, x_axis, math.rad(-30))
	Turn(tp2, x_axis, math.rad(-30))
end

-- Starbase Killed anim
function script.Killed(recentDamage, maxHealth)
	local ring, link = piece("ring", "link")
	local linkemit0, linkemit1, linkemit2 = piece("linkemit0", "linkemit1", "linkemit2")
	local bodyemit0, bodyemit1 = piece("bodyemit0", "bodyemit1")
	EmitSfx(linkemit0, 1024)
	Sleep(150 + 33)
	EmitSfx(linkemit1, 1024)
	Sleep(100 + 33)
	EmitSfx(linkemit2, 1024)
	Sleep(50 + 33)
	Hide(link)
	Spin(ring, z_axis, math.rad(-20))
	Move(ring, y_axis, 90, 12)
	Spin(body, z_axis, math.rad(10))
	Move(body, y_axis, -90, 8)
	Sleep(1200 + 33)
	EmitSfx(bodyemit0, 1025)
	EmitSfx(bodyemit1, 1026)
	Sleep(700 + 33)
	Hide(body)
	GG.RecursiveHide(unitID, info.turretIDs[4])
	Sleep(800 + 33)
	EmitSfx(info.turretIDs[1], 1024)
	EmitSfx(info.turretIDs[2], 1024)
	Sleep(120 + 33)
	EmitSfx(info.turretIDs[3], 1024)
	Sleep(300 + 33)
	EmitSfx(ring, 1025)
	Sleep(700 + 33)
	return 0
end